#!/usr/bin/env node
/**
 * Deterministic D2 diagram generator driven strictly by docs/architecture.manifest.json.
 * Usage:
 *   node scripts/gen-d2.mjs           # Write docs/architecture.d2 & docs/pipelines.d2
 *   node scripts/gen-d2.mjs --render  # Write .d2 and render .svg via `d2` CLI (if available)
 *   node scripts/gen-d2.mjs --check   # Exit non-zero if .d2 files differ from generated output
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT_DIR = resolve(import.meta.dirname, '..');
const MANIFEST_PATH = resolve(ROOT_DIR, 'docs/architecture.manifest.json');
const ARCH_D2_PATH = resolve(ROOT_DIR, 'docs/architecture.d2');
const PIPELINES_D2_PATH = resolve(ROOT_DIR, 'docs/pipelines.d2');
const ARCH_SVG_PATH = resolve(ROOT_DIR, 'docs/architecture.svg');
const PIPELINES_SVG_PATH = resolve(ROOT_DIR, 'docs/pipelines.svg');

const LAYER_META = {
  edge: { title: 'Edge / Client Delivery', fill: '#1c1917', stroke: '#fb7185' },
  app: { title: 'Application & API Pod', fill: '#18181b', stroke: '#f59e0b' },
  pipeline: { title: 'Ingestion & Batch Pipelines', fill: '#171717', stroke: '#38bdf8' },
  storage: { title: 'State & Storage', fill: '#141917', stroke: '#34d399' },
};

const BOUNDARY_STYLE = {
  shared: { badge: 'SHARED', fill: '#451a03', stroke: '#f59e0b', fontColor: '#fde68a' },
  host_routed: { badge: 'HOST_ROUTED', fill: '#1e1b4b', stroke: '#818cf8', fontColor: '#e0e7ff' },
  path_isolated: { badge: 'PATH_ISOLATED', fill: '#064e3b', stroke: '#34d399', fontColor: '#d1fae5' },
  prefix_isolated: { badge: 'PREFIX_ISOLATED', fill: '#064e3b', stroke: '#34d399', fontColor: '#d1fae5' },
};

const MODE_COLOR = {
  pull: '#fb7185',
  manual: '#f59e0b',
  cron: '#38bdf8',
  reconcile: '#34d399',
};

function d2String(value) {
  return JSON.stringify(String(value)).replace(/\$/g, '\\$');
}

function safeId(value) {
  return String(value).replace(/[^a-zA-Z0-9_]/g, '_');
}

export function buildArchitectureD2(manifest) {
  const lines = [
    '# Generated by scripts/gen-d2.mjs from docs/architecture.manifest.json. Do not edit manually.',
    'direction: right',
    '',
  ];

  const grouped = new Map();
  for (const layerKey of Object.keys(LAYER_META)) {
    grouped.set(layerKey, []);
  }
  for (const comp of manifest.components) {
    if (!grouped.has(comp.layer)) grouped.set(comp.layer, []);
    grouped.get(comp.layer).push(comp);
  }

  for (const [layerKey, comps] of grouped.entries()) {
    if (comps.length === 0) continue;
    const meta = LAYER_META[layerKey] || { title: layerKey, fill: '#1c1917', stroke: '#78716c' };
    lines.push(`${layerKey}: ${d2String(meta.title)} {`);
    lines.push(`  style.fill: ${d2String(meta.fill)}`);
    lines.push(`  style.stroke: ${d2String(meta.stroke)}`);
    lines.push(`  style.border-radius: 12`);
    for (const comp of comps) {
      const cid = safeId(comp.id);
      lines.push(`  ${cid}: ${d2String(`${comp.label}\n${comp.path}`)} {`);
      lines.push(`    shape: rectangle`);
      lines.push(`    style.border-radius: 8`);
      lines.push(`    style.fill: "#292524"`);
      lines.push(`    style.stroke: ${d2String(meta.stroke)}`);
      lines.push(`    style.font-color: "#fafaf9"`);
      lines.push('  }');
    }
    lines.push('}');
    lines.push('');
  }

  const componentLayer = new Map(manifest.components.map((c) => [c.id, `${c.layer}.${safeId(c.id)}`]));
  lines.push('# Component dependencies');
  for (const comp of manifest.components) {
    const src = componentLayer.get(comp.id);
    for (const dep of comp.dependsOn) {
      const dst = componentLayer.get(dep);
      if (src && dst) {
        lines.push(`${src} -> ${dst}`);
      }
    }
  }
  lines.push('');

  lines.push('boundaries: "Tenant Isolation Boundaries" {');
  lines.push('  grid-columns: 2');
  lines.push('  style.fill: "#0c0a09"');
  lines.push('  style.stroke: "#57534e"');
  lines.push('  style.border-radius: 12');
  for (const b of manifest.boundaries) {
    const bid = safeId(b.layer);
    const st = BOUNDARY_STYLE[b.level] || BOUNDARY_STYLE.shared;
    lines.push(`  ${bid}: ${d2String(`[${st.badge}] ${b.layer}\n${b.details}`)} {`);
    lines.push('    style.border-radius: 8');
    lines.push(`    style.fill: ${d2String(st.fill)}`);
    lines.push(`    style.stroke: ${d2String(st.stroke)}`);
    lines.push(`    style.font-color: ${d2String(st.fontColor)}`);
    lines.push('  }');
  }
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

export function buildPipelinesD2(manifest) {
  const lines = [
    '# Generated by scripts/gen-d2.mjs from docs/architecture.manifest.json. Do not edit manually.',
    'grid-columns: 1',
    'grid-gap: 24',
    '',
  ];

  for (const pipeline of manifest.pipelines) {
    const pid = safeId(pipeline.id);
    const accent = MODE_COLOR[pipeline.mode] || '#a8a29e';
    lines.push(`${pid}: ${d2String(`${pipeline.name} [${pipeline.mode.toUpperCase()}]`)} {`);
    lines.push('  direction: right');
    lines.push('  style.fill: "#1c1917"');
    lines.push(`  style.stroke: ${d2String(accent)}`);
    lines.push('  style.border-radius: 12');

    for (let i = 0; i < pipeline.steps.length; i++) {
      const step = pipeline.steps[i];
      const sid = safeId(step.id);
      const guardText = step.guards.map((g) => `Guard: ${g}`).join('\n');
      const storeText = step.stores && step.stores.length > 0 ? `\nStore: ${step.stores.join(', ')}` : '';
      const label = `${i + 1}. ${step.label}\n[${step.component}] ${step.entryPath}\n${guardText}${storeText}`;
      lines.push(`  ${sid}: ${d2String(label)} {`);
      lines.push('    style.border-radius: 8');
      lines.push('    style.fill: "#292524"');
      lines.push(`    style.stroke: ${d2String(accent)}`);
      lines.push('    style.font-color: "#fafaf9"');
      lines.push('  }');
    }

    for (let i = 0; i < pipeline.steps.length - 1; i++) {
      const curr = safeId(pipeline.steps[i].id);
      const next = safeId(pipeline.steps[i + 1].id);
      lines.push(`  ${curr} -> ${next}`);
    }

    lines.push('}');
    lines.push('');
  }

  return lines.join('\n');
}

function main() {
  const args = new Set(process.argv.slice(2));
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
  const archD2 = buildArchitectureD2(manifest);
  const pipelinesD2 = buildPipelinesD2(manifest);

  if (args.has('--check')) {
    const currentArch = existsSync(ARCH_D2_PATH) ? readFileSync(ARCH_D2_PATH, 'utf8') : '';
    const currentPipelines = existsSync(PIPELINES_D2_PATH) ? readFileSync(PIPELINES_D2_PATH, 'utf8') : '';
    if (currentArch !== archD2 || currentPipelines !== pipelinesD2) {
      console.error('D2 diagrams are out of date. Run: node scripts/gen-d2.mjs --render');
      process.exit(1);
    }
    console.log('D2 sources match docs/architecture.manifest.json.');
    return;
  }

  writeFileSync(ARCH_D2_PATH, archD2, 'utf8');
  writeFileSync(PIPELINES_D2_PATH, pipelinesD2, 'utf8');
  console.log('Generated docs/architecture.d2 and docs/pipelines.d2');

  if (args.has('--render')) {
    execFileSync('d2', ['--theme=200', '--pad=28', ARCH_D2_PATH, ARCH_SVG_PATH], { stdio: 'inherit' });
    execFileSync('d2', ['--theme=200', '--pad=28', PIPELINES_D2_PATH, PIPELINES_SVG_PATH], { stdio: 'inherit' });
    console.log('Rendered docs/architecture.svg and docs/pipelines.svg');
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
